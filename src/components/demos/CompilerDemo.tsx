"use client";

import { useId, useState } from "react";
import Image from "next/image";
import { ChevronLeft, ChevronRight, Download, Minus, Plus } from "lucide-react";
import recordings from "@/data/compiler-recordings.json";
import { withBasePath } from "@/lib/utils";
import styles from "./Demos.module.css";

const stages = [
  { title: "Source", explanation: "A small Java-like program enters the compiler. Flex scans the tokens and Bison parses the grammar." },
  { title: "Syntax tree", explanation: "The parser builds syntax-tree nodes. This is the compiler's emitted tree, rendered with Graphviz." },
  { title: "Control flow", explanation: "C++ visitors check semantics and build basic blocks connected by branches and loop edges." },
  { title: "Intermediate code", explanation: "Operations become three-address instructions. This listing is the recorded output.ir file." },
  { title: "Bytecode", explanation: "The compiler lowers the program into instructions for its custom virtual machine." },
  { title: "Execution", explanation: "The project's interpreter executes the generated bytecode and prints the result shown below." },
];

export default function CompilerDemo() {
  const id = useId();
  const [exampleId, setExampleId] = useState(recordings[0].id);
  const [stage, setStage] = useState(0);
  const [zoom, setZoom] = useState(1);
  const example = recordings.find(item => item.id === exampleId)!;
  const graph = stage === 1 ? example.tree : example.cfg;
  const changeStage = (next: number) => { setStage(next); setZoom(1); };

  return (
    <div className={styles.demo} data-demo="compiler">
      <div className={styles.toolbar}>
        <label className={styles.field} htmlFor={`${id}-example`}>Choose a program
          <select id={`${id}-example`} value={exampleId} onChange={event => { setExampleId(event.target.value); changeStage(0); }}>
            {recordings.map(item => <option key={item.id} value={item.id}>{item.title}</option>)}
          </select>
        </label>
        <p className={styles.context}>Recorded runs from the jointly developed C++ compiler. Select a stage to inspect its real output.</p>
      </div>
      <ol className={styles.pipeline} aria-label="Compiler stages">
        {stages.map((item, index) => (
          <li key={item.title}><button type="button" aria-current={stage === index ? "step" : undefined} onClick={() => changeStage(index)}>
            <span>{index + 1}</span>{item.title}
          </button></li>
        ))}
      </ol>
      <div className={styles.compilerWorkspace}>
        <section className={styles.sourcePane} aria-labelledby={`${id}-source`}>
          <h3 id={`${id}-source`}>Input program</h3>
          <pre tabIndex={0} aria-label="Source program"><code>{example.source}</code></pre>
          <p className={styles.context}>{example.note}</p>
        </section>
        <section className={styles.artifactPane} aria-labelledby={`${id}-stage`}>
          <h3 id={`${id}-stage`}>{stages[stage].title}</h3>
          <p className={styles.explanation}>{stages[stage].explanation}</p>
          {(stage === 1 || stage === 2) ? (
            <>
              <div className={styles.graphTools}>
                <span>Diagram zoom</span>
                <button type="button" className={styles.iconButton} disabled={zoom <= 1} onClick={() => setZoom(value => Math.max(1, value - 0.5))} aria-label="Zoom diagram out"><Minus size={16} /></button>
                <output aria-live="polite">{Math.round(zoom * 100)}%</output>
                <button type="button" className={styles.iconButton} disabled={zoom >= 3} onClick={() => setZoom(value => Math.min(3, value + 0.5))} aria-label="Zoom diagram in"><Plus size={16} /></button>
              </div>
              <div className={styles.graphViewport} tabIndex={0} aria-label={`${stages[stage].title} diagram, scroll to explore when zoomed`}>
                <div style={{ width: `${zoom * 100}%`, minHeight: "100%" }}>
                  <Image src={withBasePath(graph)} width={900} height={650} alt={`${example.title}: compiler-generated ${stages[stage].title.toLowerCase()}`} unoptimized className={styles.graphImage} style={{ height: 320 * zoom }} />
                </div>
              </div>
              <a className={styles.textLink} href={withBasePath(graph)} download><Download size={15} /> Download this SVG</a>
            </>
          ) : stage === 5 ? (
            <div className={styles.execution}>
              <span>Interpreter output</span>
              <output className={styles.result} aria-live="polite">{example.expected}</output>
              <p>The generated bytecode completed in the project&apos;s interpreter.</p>
              <details><summary>View the recorded interpreter trace</summary><pre tabIndex={0}><code>{example.stdout}</code></pre></details>
            </div>
          ) : (
            <pre className={styles.codeOutput} tabIndex={0} aria-label={stage === 0 ? "Compiler input" : stages[stage].title}>
              <code>{stage === 0 ? example.source : stage === 3 ? example.ir : example.bytecode}</code>
            </pre>
          )}
        </section>
      </div>
      <div className={styles.stageControls}>
        <button type="button" className={styles.secondaryButton} onClick={() => changeStage(stage - 1)} disabled={stage === 0}><ChevronLeft size={16} /> Previous stage</button>
        <p role="status">Stage {stage + 1} of {stages.length}</p>
        <button type="button" className={styles.primaryButton} onClick={() => changeStage(stage + 1)} disabled={stage === stages.length - 1}>Next stage <ChevronRight size={16} /></button>
      </div>
    </div>
  );
}
